#!/usr/bin/env node
// scripts/sync-mock-images.mjs
// Scans public/images/mock/profiles/<slug>/ for avatar.jpg|png|webp and work-1..work-8 (.jpg|png|webp),
// and writes data/mock/mock-images.generated.ts exporting a map slug -> { avatar?: string; works: string[] }.
// Must exit 0 and do nothing if public/images/mock or data/mock does not exist (so it survives mock removal).

import { existsSync, readdirSync, writeFileSync } from "fs";
import { join, resolve } from "path";
import { fileURLToPath } from "url";

const __dirname = resolve(fileURLToPath(import.meta.url), "..");
const ROOT = resolve(__dirname, "..");

const mockImagesDir = join(ROOT, "public", "images", "mock", "profiles");
const mockDataDir = join(ROOT, "data", "mock");
const outputFile = join(mockDataDir, "mock-images.generated.ts");

if (!existsSync(mockImagesDir) || !existsSync(mockDataDir)) {
  // Exit gracefully if mock folders were stripped in production
  process.exit(0);
}

const EXT_REGEX = /\.(jpg|jpeg|png|webp)$/i;

const profilesMap = {};

try {
  const profileFolders = readdirSync(mockImagesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);

  for (const slug of profileFolders) {
    const slugDir = join(mockImagesDir, slug);
    const files = readdirSync(slugDir);

    let avatar;
    const worksMap = new Map();

    for (const file of files) {
      if (!EXT_REGEX.test(file)) continue;

      if (/^avatar\.(jpg|jpeg|png|webp)$/i.test(file)) {
        avatar = `/images/mock/profiles/${slug}/${file}`;
        continue;
      }

      const workMatch = file.match(/^work-([1-8])\.(jpg|jpeg|png|webp)$/i);
      if (workMatch) {
        const index = parseInt(workMatch[1], 10);
        worksMap.set(index, `/images/mock/profiles/${slug}/${file}`);
      }
    }

    // Sort work photos numerically 1..8
    const sortedWorks = Array.from(worksMap.entries())
      .sort((a, b) => a[0] - b[0])
      .map((entry) => entry[1]);

    profilesMap[slug] = {
      avatar,
      works: sortedWorks,
    };
  }
} catch (err) {
  console.error("Warning: sync-mock-images encountered an error:", err.message);
}

const fileHeader = `// AUTO-GENERATED by scripts/sync-mock-images.mjs. Do not edit directly.
export interface MockProfileImages {
  avatar?: string;
  works: string[];
}

export const MOCK_IMAGES_MAP: Record<string, MockProfileImages> = ${JSON.stringify(
  profilesMap,
  null,
  2
)};
`;

writeFileSync(outputFile, fileHeader, "utf8");
console.log(`[sync-mock-images] Synced mock images for ${Object.keys(profilesMap).length} profiles.`);
